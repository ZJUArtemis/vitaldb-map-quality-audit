# ═══════════════════════ FIG 4 : M1 subgroup forest (ARC test) ════════════════
print("\n[Fig4] M1 subgroup forest (ARC test n=159)")
te2 = te.copy(); te2['_p'] = proba_te['M1']; te2['_y'] = y_te
subs = [('Overall', np.ones(len(te2), bool))]
subs += [('Age < 65', te2['age'] < 65), ('Age $\\geq$ 65', te2['age'] >= 65)]
subs += [('Male', te2['sex'] == 'M'), ('Female', te2['sex'] == 'F')]
