# ═══════════════════════ SUPP FIG 4 : DCA M0-M4 (ARC test) ════════════════════
print("\n[SuppFig4] Decision curve analysis (ARC test n=159)")
def net_benefit(y_true, p, pt):
    y_true = np.asarray(y_true); n = len(y_true)
    pred = p >= pt
    tp = np.sum(pred & (y_true == 1)); fp = np.sum(pred & (y_true == 0))
    return tp/n - fp/n * (pt/(1-pt))
pts = np.linspace(0.01, 0.70, 70)
prev = y_te.mean()
fig, ax = plt.subplots(figsize=(6.3, 4.6))
ax.plot(pts, [prev - (1-prev)*(t/(1-t)) for t in pts], color='#bbb', ls=':', lw=1.2, label='Treat all')
ax.axhline(0, color='#333', ls='--', lw=1, label='Treat none')
for m in ['M0', 'M1', 'M3', 'M4']:
    nb = [net_benefit(y_te, proba_te[m], t) for t in pts]
    ax.plot(pts, nb, color=COL[m], lw=2 if m in ('M1','M3') else 1.4, label=f'{m} ({labels[m].split(": ")[1]})')
ax.set_xlabel('Threshold probability'); ax.set_ylabel('Net benefit')
ax.set_ylim(-0.05, max(prev+0.02, 0.3)); ax.set_xlim(0, 0.7)
ax.set_title('Decision curve analysis — nested models, ARC test set ($n$=159)', fontsize=9, fontweight='bold')
