y_tr, y_te = tr['crash_30'].values, te['crash_30'].values
print(f"ARC N={len(arc)} events={int(y_all.sum())} | Train={len(tr)} Test={len(te)} (events={int(y_te.sum())})")

def pipe():
    return Pipeline([('imp', SimpleImputer(strategy='median')),
                     ('sc', StandardScaler()),
                     ('lr', LogisticRegression(max_iter=1000, random_state=42))])

MODELS = {
    'M0': CLIN,
    'M1': CLIN + ['baseline_map'],
    'M2': CLIN + ['ri_mean_clean'],
    'M3': CLIN + ['baseline_map', 'ri_mean_clean'],
    'M4': CLIN + ['baseline_map', 'ri_mean_clean', 'ppg_amp_clean'],
}
# fit all, keep test probabilities
proba_te, auc_te = {}, {}
for m, fs in MODELS.items():
    p = pipe(); p.fit(tr[fs].values, y_tr)
    proba_te[m] = p.predict_proba(te[fs].values)[:, 1]
    auc_te[m] = roc_auc_score(y_te, proba_te[m])
print("  ARC test AUROC:", {m: round(a, 3) for m, a in auc_te.items()})

def boot_ci(yt, ys, n=1000, seed=0):
    r = np.random.default_rng(seed); a = []
    yt = np.asarray(yt); ys = np.asarray(ys)
    for _ in range(n):
        idx = r.choice(len(yt), len(yt), replace=True)
        if len(np.unique(yt[idx])) < 2: continue
        a.append(roc_auc_score(yt[idx], ys[idx]))
    return (np.percentile(a, 2.5), np.percentile(a, 97.5)) if a else (np.nan, np.nan)

