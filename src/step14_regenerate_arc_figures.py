# ═══════════════════════ SUPP FIG 6 : M1/M3 AUROC by RI tertile (ARC test) ════
print("\n[SuppFig6] M1 & M3 AUROC by RI tertile (ARC test)")
ri_te = te['ri_mean_clean'].values
# tertile edges from full ARC RI (clean), applied to test
edges = np.nanpercentile(arc['ri_mean_clean'].dropna().values, [33.333, 66.667])
def tert(v):
    if np.isnan(v): return -1
    return 0 if v <= edges[0] else (1 if v <= edges[1] else 2)
tlab = ['T1 (low RI)', 'T2 (mid RI)', 'T3 (high RI)']
groups = {}
for ti in range(3):
    mask = np.array([tert(v) == ti for v in ri_te])
    groups[ti] = mask
fig, ax = plt.subplots(figsize=(6.2, 4.3))
width = 0.36
xs = np.arange(3)
for j, m in enumerate(['M1', 'M3']):
    vals, los, his, ns = [], [], [], []
    for ti in range(3):
        mask = groups[ti]; yy = y_te[mask]; pp = proba_te[m][mask]
        ns.append(int(mask.sum()))
        if len(np.unique(yy)) < 2 or yy.sum() < 3 or (len(yy)-yy.sum()) < 3:
            vals.append(np.nan); los.append(np.nan); his.append(np.nan); continue
        a = roc_auc_score(yy, pp); lo, hi = boot_ci(yy, pp, seed=3)
        vals.append(a); los.append(a-lo); his.append(hi-a)
    off = (j-0.5)*width
    ax.bar(xs+off, vals, width, color=COL[m], label=m, edgecolor='white',
           yerr=[np.nan_to_num(los), np.nan_to_num(his)], capsize=3)
ax.set_xticks(xs); ax.set_xticklabels([f"{tlab[i]}\n(n={int(groups[i].sum())})" for i in range(3)], fontsize=8)
ax.set_ylabel('AUROC (ARC test set)'); ax.set_ylim(0, 1.05)
ax.axhline(0.5, color='#999', ls='--', lw=0.8)
ax.set_title('M1 vs M3 AUROC stratified by reflection-index tertile (ARC test)\n'
             'RI adds no discrimination within any tertile', fontsize=9, fontweight='bold')
ax.legend(fontsize=8, loc='lower right')
save(fig, "suppfig6_ritertile_arc")

